import { nodeKebab, serviceNodes } from '../nodes';
import type { DesignDoc } from '../schemas/design';
import type { RequirementsDoc } from '../schemas/requirements';
import type { MatrixRow } from '../trace';
import { linkLabel, renderAll } from './mermaid';

export const GENERATED_HEADER = '<!-- generated by AISE from .aise/*.json, do not edit -->';

const fence = (mermaid: string): string => `\`\`\`mermaid\n${mermaid}\n\`\`\``;

const refs = (reqIds: string[]): string => (reqIds.length > 0 ? ` (${reqIds.join(', ')})` : '');

function bulletSection(heading: string, items: string[]): string[] {
	return items.length > 0 ? [`## ${heading}`, '', ...items.map((i) => `- ${i}`), ''] : [];
}

export function requirementsMarkdown(r: RequirementsDoc): string {
	const lines = [GENERATED_HEADER, '', '# Requirements', ''];
	for (const req of r.requirements) {
		lines.push(
			`## ${req.id} ${req.title}`,
			'',
			`${req.type}, ${req.priority}`,
			'',
			req.text,
			'',
			'Acceptance criteria:',
			'',
			...req.acceptanceCriteria.map((c) => `- ${c}`),
			''
		);
	}
	lines.push(
		...bulletSection(
			'Open questions',
			r.openQuestions.map((q) => `${q.id}: ${q.text}${refs(q.reqIds)}`)
		)
	);
	lines.push(...bulletSection('Assumptions', r.assumptions));
	lines.push(...bulletSection('Out of scope', r.outOfScope));
	return lines.join('\n').trimEnd() + '\n';
}

export function designMarkdown(d: DesignDoc, title: string): string {
	const all = renderAll(d, title);
	const named = (id: string) => `${id} ${d.nodes.find((n) => n.id === id)?.name ?? ''}`.trim();
	const lines = [
		GENERATED_HEADER,
		'',
		`# ${title}: design`,
		'',
		'## Use cases',
		'',
		fence(all.useCase),
		'',
		'## Classes',
		'',
		fence(all.class),
		'',
		'## Sequences',
		''
	];
	for (const s of all.sequences) lines.push(`### ${s.id} ${s.name}`, '', fence(s.mermaid), '');
	lines.push('## Deployment', '', fence(all.deployment), '');
	const elements = [
		...d.actors.map((a) => `${a.id} ${a.name} (actor)`),
		...d.useCases.map((u) => `${u.id} ${u.name} (use case)${refs(u.reqIds)}`),
		...d.classes.map((c) => `${c.id} ${c.name} (${c.kind})${refs(c.reqIds)}`),
		...d.components.map((c) => `${c.id} ${c.name} (component)${refs(c.reqIds)}`),
		...d.nodes.map((n) => `${n.id} ${n.name} (${n.kind} node)${refs(n.reqIds)}`),
		...d.links.map((l) => `${named(l.from)} to ${named(l.to)} (${linkLabel(l)})`)
	];
	lines.push(...bulletSection('Elements', elements));
	return lines.join('\n').trimEnd() + '\n';
}

/** One line of text: every run of whitespace, newlines included, becomes one space. */
const oneLine = (s: string): string => s.replace(/\s+/g, ' ');
/** A table cell on one line, with backslashes and then pipes escaped. */
const cell = (s: string): string => oneLine(s).replaceAll('\\', '\\\\').replaceAll('|', '\\|');
const listCell = (items: string[]): string => (items.length > 0 ? cell(items.join(', ')) : 'none');

/**
 * `README.md` of a generated project: how to run it and which file holds which design class, with
 * the class's requirements. Rendered from the design, so it never drifts from it.
 * `paths` maps a class ID to its planned file; `db` is the default database file, or null.
 * `runDoc` says whether `RUN.md` exists, so the README links to it.
 */
export function readmeMarkdown(
	d: DesignDoc,
	title: string,
	paths: Record<string, string>,
	db: string | null,
	runDoc = false
): string {
	const lines = [
		GENERATED_HEADER,
		'',
		`# ${oneLine(title)}`,
		'',
		'Generated by AISE from the approved design. Requirements: [docs/requirements.md](docs/requirements.md), design and diagrams: [docs/design.md](docs/design.md).',
		'',
		...(runDoc ? ['Run it with Docker: see [RUN.md](RUN.md).', ''] : []),
		'## Run',
		'',
		'```sh',
		'npm ci',
		'npm start          # http://localhost:8080, PORT changes the port',
		...serviceNodes(d)
			.filter((r) => !r.primary)
			.map(
				(r) =>
					`npm run start:${nodeKebab(r.node)}   # ${oneLine(r.node.name)}, http://localhost:${r.port}, ${r.portVar} changes the port`
			),
		'npm test',
		'npm run typecheck',
		'```',
		''
	];
	if (db)
		lines.push(
			`Data is stored in \`${db}\`. \`DB_PATH\` changes the file; \`DB_PATH=:memory:\` keeps it in memory.`,
			''
		);
	lines.push(
		'## Structure',
		'',
		'`src/app/` wires the classes into an Express app and `src/app/main.ts` starts it; `public/` holds the web page. The JSDoc of each class carries a `@trace` tag naming its design element and requirements.',
		''
	);
	for (const comp of d.components) {
		const classes = d.classes.filter((c) => comp.classIds.includes(c.id) && paths[c.id]);
		if (classes.length === 0) continue;
		lines.push(
			`## ${oneLine(comp.name)} (${comp.id})`,
			'',
			'| Class | File | Design | Requirements | Purpose |',
			'| --- | --- | --- | --- | --- |',
			...classes.map(
				(c) =>
					`| ${cell(c.name)} | \`${paths[c.id]}\` | ${c.id} | ${listCell(c.reqIds)} | ${cell(c.description)} |`
			),
			''
		);
	}
	return lines.join('\n').trimEnd() + '\n';
}

/** `2 passed, 1 failed`, counted per status in a fixed order. */
function testCounts(tests: MatrixRow['tests']): string {
	const order = ['passed', 'failed', 'todo'] as const;
	const parts = order
		.map((s) => [tests.filter((t) => t.status === s).length, s] as const)
		.filter(([n]) => n > 0)
		.map(([n, s]) => `${n} ${s}`);
	return parts.length > 0 ? parts.join(', ') : 'none';
}

/** The trace matrix as one Markdown table (`docs/trace.md`), deterministic for the same input. */
export function traceMarkdown(
	rows: MatrixRow[],
	title: string,
	tests: { at: string; outOfDate: boolean } | null
): string {
	const when = tests
		? `Test results from ${tests.at}${tests.outOfDate ? ' (out of date: code or tests changed since)' : ''}.`
		: 'No test results yet.';
	const lines = [
		GENERATED_HEADER,
		'',
		`# ${oneLine(title)}: traceability`,
		'',
		when,
		'',
		'| Requirement | Design | Code | Tests | Gaps |',
		'| --- | --- | --- | --- | --- |'
	];
	for (const r of rows) {
		const gaps = [r.noDesign ? 'no design' : '', r.noTest ? 'no test' : ''].filter(Boolean);
		lines.push(
			`| ${cell(`${r.reqId} ${r.title}`)} | ${listCell(r.design)} | ${listCell(r.files)} | ${testCounts(r.tests)} | ${listCell(gaps)} |`
		);
	}
	return lines.join('\n') + '\n';
}
